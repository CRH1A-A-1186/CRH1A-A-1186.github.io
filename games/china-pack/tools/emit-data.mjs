// Emit the PROVS / ADJ / REGION_DEFS / COLORS data block that the game reads.
//
// Input : data/china-pack.json   (from tools/build-pack.mjs)
// Output: src/pack-data.js       (spliced into the bundle by tools/bundle.mjs)
//
// Run: node tools/emit-data.mjs      (from the china-pack directory)
import fs from 'node:fs';

const pack = JSON.parse(fs.readFileSync('data/china-pack.json', 'utf8'));

// Labels: what gets drawn on a piece (short), plus the official name used in text.
const SHORT = {
  110000: '北京', 120000: '天津', 130000: '河北', 140000: '山西', 150000: '内蒙古',
  210000: '辽宁', 220000: '吉林', 230000: '黑龙江',
  310000: '上海', 320000: '江苏', 330000: '浙江', 340000: '安徽', 350000: '福建',
  360000: '江西', 370000: '山东', 710000: '台湾',
  410000: '河南', 420000: '湖北', 430000: '湖南', 440000: '广东', 450000: '广西',
  460000: '海南', 810000: '香港', 820000: '澳门',
  500000: '重庆', 510000: '四川', 520000: '贵州', 530000: '云南', 540000: '西藏',
  610000: '陕西', 620000: '甘肃', 630000: '青海', 640000: '宁夏', 650000: '新疆',
};

// Region grouping: the conventional divisions.
// 香港 and 澳门 only touch 广东, so they belong to the same region as it, otherwise the
// grouping would not be a connected area.
// 海南 and 台湾 are single-province regions (islands with no provincial neighbours), like
// Hokkaido in the original pack: they only supply a colour, and are never completable.
const REGIONS = [
  { key: 'db', name: '东北地区', codes: [210000, 220000, 230000] },
  { key: 'hb', name: '华北地区', codes: [110000, 120000, 130000, 140000, 150000] },
  { key: 'hd', name: '华东地区', codes: [310000, 320000, 330000, 340000, 350000, 360000, 370000] },
  { key: 'zn', name: '中南地区', codes: [410000, 420000, 430000, 440000, 450000, 810000, 820000] },
  { key: 'xn', name: '西南地区', codes: [500000, 510000, 520000, 530000, 540000] },
  { key: 'xb', name: '西北地区', codes: [610000, 620000, 630000, 640000, 650000] },
  { key: 'hn', name: '海南省', codes: [460000], single: true },
  { key: 'tw', name: '台湾省', codes: [710000], single: true },
];

// Pale region colours, neighbouring regions kept apart in hue (Style B of the original).
const COLORS = {
  db: '#c6ddf1', hb: '#d0e8ba', hd: '#f6cbc4', zn: '#f2e1a2',
  xn: '#dacdf0', xb: '#f8d2a9', hn: '#b9e2d5', tw: '#edbacb',
};

const byCode = new Map(pack.provinces.map((p) => [p.code, p]));
const regionCodes = new Map(REGIONS.map((r) => [r.key, r.codes.slice()]));
const covered = new Set();
for (const [key, codes] of regionCodes) {
  for (const c of codes) {
    if (!byCode.has(c)) throw new Error(`region ${key} claims missing code ${c}`);
    if (covered.has(c)) throw new Error(`code ${c} in two regions`);
    covered.add(c);
  }
}
if (covered.size !== 34) throw new Error(`regions cover ${covered.size} provinces, expected 34`);
for (const p of pack.provinces) if (!covered.has(p.code)) throw new Error(`province ${p.code} in no region`);

// ---- emit the PROVS table ----
// [code, name, label, real area km2, [x0, y0, x1, y1, ...] rings in km, shared equirectangular frame, y grows south]
const lines = [];
lines.push('/*PACK-BEGIN*/');
lines.push('// Generated by tools/emit-data.mjs from data/china-pack.json (DataV.GeoAtlas boundaries).');
lines.push('// [code, official name, short label, real land area in km2, [x0, y0, x1, y1, ...] rings in km,');
lines.push('//  shared equirectangular projection (lat0 ' + pack.frame.LAT0 + '), y grows south]. Do not edit by hand.');
lines.push('const PROVS = [');
for (const p of pack.provinces.slice().sort((a, b) => a.code - b.code)) {
  const rings = p.rings.map((r) => `[${r.map(([x, y]) => `${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`).join(',')}]`).join(',');
  lines.push(`[${p.code},"${p.name}","${SHORT[p.code]}",${Math.round(p.km2)},[${rings}]],`);
}
lines.push('];');
lines.push('const ADJ = [' + pack.adj.map(([a, b]) => `[${a},${b}]`).join(',') + '];');
lines.push(`const REGION_DEFS = ${JSON.stringify(REGIONS.map((r) => ({ key: r.key, name: r.name, single: !!r.single, codes: regionCodes.get(r.key) })))};`);
lines.push(`const COLORS = ${JSON.stringify(COLORS)};`);
lines.push('/*PACK-END*/');

fs.writeFileSync('src/pack-data.js', lines.join('\n') + '\n', 'utf8');
console.log('provinces:', pack.provinces.length, 'adjacency pairs:', pack.adj.length, 'regions:', REGIONS.length);
console.log('region sizes:', REGIONS.map((r) => `${r.name}=${regionCodes.get(r.key).length}`).join(' '));
console.log('wrote src/pack-data.js', fs.statSync('src/pack-data.js').size, 'bytes');
